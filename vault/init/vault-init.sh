#!/bin/sh
# vault-init: one-shot bootstrap of the dev Vault. Idempotent: safe to run again.
#   1. audit log   2. secrets (random values made by Vault)   3. policies
#   4. AppRole roles   5. each client's login files, in its own volume
#   6. a token for Prometheus (read sys/metrics only)
# It never prints a secret value.
set -eu

log() { echo "vault-init: $*"; }

APP_DIR=/bootstrap/democyber           # read by democyber (UID 10001)
AGENT_DIR=/bootstrap/grafana           # read by Grafana's Vault Agent (user vault)
PROM_DIR=/bootstrap/prometheus         # read by Prometheus (user nobody)
SECRETS_DIR=/bootstrap/grafana-secrets # written by the Vault Agent, read by Grafana

APP_UID=10001
PROM_UID=65534
AGENT_UID=$(id -u vault)               # same image as the agent, so same UID

# write_file <path> <owner-uid>: stdin -> file readable by its owner only (mode 0400).
# Written to a temporary file first, then renamed: the client never sees half a file.
write_file() {
  tmp="$1.tmp"
  cat > "$tmp"
  chmod 0400 "$tmp"
  chown "$2" "$tmp"
  mv -f "$tmp" "$1"
}

log "waiting for Vault at $VAULT_ADDR"
tries=0
until vault status > /dev/null 2>&1; do
  tries=$((tries + 1))
  if [ "$tries" -gt 60 ]; then
    log "Vault is not ready after 60 s"
    exit 1
  fi
  sleep 1
done

# 1. Audit device: one JSON line per request; secret values are HMAC-hashed
if vault audit list -format=json 2> /dev/null | grep -q '"file/"'; then
  log "audit device: already enabled"
else
  vault audit enable file file_path=/vault/logs/audit.log > /dev/null
  log "audit device: enabled (/vault/logs/audit.log)"
fi

# 2. Secrets in KV v2 (the "secret/" engine of dev mode), created only if missing.
#    The value is generated by Vault, kept in a shell variable and sent on stdin ("key=-"):
#    it is never an argument of a command and never printed.
create_secret() { # create_secret <path> <key>
  if vault kv get "$1" > /dev/null 2>&1; then
    log "$1: already exists (kept)"
  else
    value=$(vault write -field=random_bytes sys/tools/random/32 format=hex)
    printf '%s' "$value" | vault kv put "$1" "$2=-" > /dev/null
    value=""
    log "$1: created with a random value"
  fi
}
create_secret secret/democyber api-key
create_secret secret/grafana admin-password

# 3. Policies: each client can read one path, read-only
for policy in democyber grafana metrics; do
  vault policy write "$policy" "/vault/policies/$policy.hcl" > /dev/null
done
log "policies: democyber, grafana, metrics"

# 4. AppRole: login for machines. Short-lived tokens (10 min, renewable up to 30 min).
#    Demo trade-off: the secret-id never expires and can be reused, so a client can log in
#    again after a restart. In production: single-use or response-wrapped secret-ids.
if ! vault auth list -format=json | grep -q '"approle/"'; then
  vault auth enable approle > /dev/null
fi
for role in democyber grafana; do
  vault write "auth/approle/role/$role" \
    token_policies="$role" token_ttl=10m token_max_ttl=30m \
    secret_id_ttl=0 secret_id_num_uses=0 > /dev/null
done
log "approle: roles democyber and grafana"

# 5. Login files, rewritten at every run, each in its client's own volume
give_login() { # give_login <role> <dir> <owner-uid>
  role_id=$(vault read -field=role_id "auth/approle/role/$1/role-id")
  secret_id=$(vault write -f -field=secret_id "auth/approle/role/$1/secret-id")
  printf '%s' "$role_id" | write_file "$2/role-id" "$3"
  printf '%s' "$secret_id" | write_file "$2/secret-id" "$3"
  role_id=""
  secret_id=""
  log "$1: login files written for UID $3"
}
give_login democyber "$APP_DIR" "$APP_UID"
give_login grafana "$AGENT_DIR" "$AGENT_UID"

# The agent writes Grafana's password file into this folder: it must own it
if [ "$(stat -c %u "$SECRETS_DIR")" != "$AGENT_UID" ]; then
  chmod 0755 "$SECRETS_DIR"
  chown "$AGENT_UID" "$SECRETS_DIR"
fi

# 6. Prometheus token: policy "metrics" only, valid 30 days
metrics_token=$(vault token create -policy=metrics -orphan -ttl=720h -display-name=prometheus -field=token)
printf '%s' "$metrics_token" | write_file "$PROM_DIR/vault-token" "$PROM_UID"
metrics_token=""
log "prometheus: metrics token written"

log "done"
